import Foundation

/// 파트너 경험치·알 계량기의 환율표. 진화 자체는 더 이상 경험치 임계가 아니라 조건
/// (레벨·도구·친밀도 등, `PlayerStore+Evolution`)이 게이트다 — 여기 남은 것은 경험치가
/// 어떻게 쌓이는지와, 알 하나를 부르는 값어치뿐이다.
enum ExpBalance {
    /// 토큰 몇 개가 1EXP 인가. **이 앱의 손잡이**이고, 곡선은 본가 값 그대로다.
    ///
    /// 2000인 근거(실측 기반): `mediumFast` 만렙이 20억 토큰이 되어, 하루 3.65억을 쓰는 사용자는
    /// 한 마리에 약 5.5일, 하루 1.5B 를 쓰는 헤비 사용자도 32시간이 걸린다. **레벨이 긴
    /// 프로젝트가 되고 알이 꾸준한 보상이 되도록** 벌린 값이다.
    ///
    /// 500 이었을 때의 문제 둘: ① 헤비 사용자가 8시간이면 만렙을 찍었고 파이리는 1분 만에
    /// 리자드가 돼 1단계를 볼 틈이 없었다. ② `mediumFast` 만렙이 5억 토큰으로 **커먼 알 임계와
    /// 정확히 같아서**, 커먼 파트너는 만렙과 알을 같은 순간에 찍었다 — 두 계량기를 분리한 것이
    /// 화면에서 안 보였다. 지금은 만렙이 커먼 알의 4배다.
    static let tokensPerExp = 2000

    /// 경험치 사탕 하나가 주는 EXP.
    ///
    /// **토큰으로 못 박아 파생시킨다.** 사탕의 상점 가격은 안 바뀌었으므로 값어치도 안 바뀌어야
    /// 하는데, 상수로 적어 두면 환율을 조정할 때마다 사탕만 조용히 몇 배가 된다(500 → 2000 으로
    /// 옮길 때 실제로 4배가 될 뻔했다).
    static let candyTokens = 100_000_000
    static var candyExp: Int { candyTokens / tokensPerExp }

    /// 알 하나를 발견할 값어치. 등급이 오를 때마다 두 배.
    ///
    /// 왜 비싼가: 상점 뽑기(1000만 토큰)가 무엇이 나올지 모르는 값이라면, 이쪽은 무엇이 나올지
    /// 아는 값이다 — 커먼 알 하나가 뽑기 50번어치다. 다 키운 아이를 곁에 오래 두는 것에만
    /// 열리는 길이라, 흔하면 그 무게가 사라진다.
    static func eggThreshold(grade: Grade) -> Int {
        switch grade {
        case .common: 500_000_000
        case .rare: 1_000_000_000
        case .epic: 2_000_000_000
        case .legendary: 4_000_000_000
        }
    }
}
