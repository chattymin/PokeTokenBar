import Foundation

/// 파트너 경험치·알 계량기의 환율표. 진화 자체는 더 이상 경험치 임계가 아니라 조건
/// (레벨·도구·친밀도 등, `PlayerStore+Evolution`)이 게이트다 — 여기 남은 것은 경험치가
/// 어떻게 쌓이는지와, 알 하나를 부르는 값어치뿐이다.
enum ExpBalance {
    /// 토큰 몇 개가 1EXP 인가. **이 앱의 손잡이**이고, 곡선은 본가 값 그대로다.
    ///
    /// 8000인 근거(실사용 관찰 + 실측): `mediumFast` 기준 **L50 이 하루 3.65억 사용자에게 2.7일**,
    /// 하루 1.5B 헤비 사용자에게 16시간이다. 50 위로는 사실상 아무도 안 올리므로 그 언저리가
    /// 실질 목표점이고, L100(8B 토큰 · 22일)은 트로피로 남는다.
    ///
    /// **바닥 구간이 정한 값이다.** 세제곱 곡선은 아래쪽이 거의 평평해서(L1→L2 가 8EXP) 환율이
    /// 낮으면 레벨이 초 단위로 튄다 — 2000일 때 실사용 관찰이 "1초에 2~3렙"이었고, 계산해 보면
    /// 활동 중 버스트(초당 19.5k 토큰)에서 L1→L2 가 0.8초, L2→L3 가 1.9초였다. 8000에서는
    /// 3.3초 / 7.8초가 되어 한 레벨씩 읽힌다. **이건 환율로만 늦출 수 있고 곡선으로는 못 고친다** —
    /// 바닥이 평평한 것이 본가 곡선의 성질이라, 손대면 그 곡선을 쓰는 이유가 없어진다.
    ///
    /// 지나온 값: 500(너무 빠름 — 헤비가 8시간에 만렙, 커먼 알 임계와 만렙이 같은 값) →
    /// 2000(저렙이 초 단위로 튐) → 8000.
    ///
    /// **이미 1.7.0 을 쓰던 세이브는 레벨이 안 떨어진다.** 이전(`Individual.init(from:)`)은
    /// `eggProgress` 키가 **없을 때만** 도는데 그 세이브엔 이미 있다 — 쌓인 경험치는 그대로고
    /// 앞으로의 속도만 느려진다.
    static let tokensPerExp = 8000

    /// 경험치 사탕 하나가 주는 EXP.
    ///
    /// **토큰으로 못 박아 파생시킨다.** 사탕의 상점 가격은 안 바뀌었으므로 값어치도 안 바뀌어야
    /// 하는데, 상수로 적어 두면 환율을 조정할 때마다 사탕만 조용히 몇 배가 된다(500 → 2000 으로
    /// 옮길 때 실제로 4배가 될 뻔했다).
    static let candyTokens = 100_000_000
    static var candyExp: Int { candyTokens / tokensPerExp }

    /// 알 하나를 발견할 값어치. 등급이 오를 때마다 두 배.
    ///
    /// 왜 비싼가: 상점 뽑기(1000만 토큰)가 무엇이 나올지 모르는 값이라면, 이쪽은 무엇이 나올지
    /// 아는 값이다 — 커먼 알 하나가 뽑기 50번어치다. 다 키운 아이를 곁에 오래 두는 것에만
    /// 열리는 길이라, 흔하면 그 무게가 사라진다.
    static func eggThreshold(grade: Grade) -> Int {
        switch grade {
        case .common: 500_000_000
        case .rare: 1_000_000_000
        case .epic: 2_000_000_000
        case .legendary: 4_000_000_000
        }
    }
}
