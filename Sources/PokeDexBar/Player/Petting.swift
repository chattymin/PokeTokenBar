import Foundation

/// 쓰다듬기 — 펫을 **길게 누르고 있는 동안** 파트너와 함께한 시간이 쌓인다.
///
/// **숨은 조작이다.** 어디에도 안 적혀 있고, 펫을 세 번 두드리면 따라큐의 탈이 깨지는
/// 것(`BrokenForm`)과 같은 자리에 산다 — 이미 "펫을 만지면 반응한다"는 것을 배운 사람이
/// 자연히 시도해 볼 동작이라, 발견되면 설명이 필요 없다.
///
/// 원작에 대응물이 있다: 마사지사와 포켓 리프레시가 친밀도를 직접 올려 준다. 그래서
/// **문턱을 낮추지 않고 시간을 더한다** — 리본 사다리(1·7·30·90일)는 사탕 생산 속도와
/// 채집 확률을 정하는 경제 축이라, 문턱을 건드리면 그 사다리 전체가 조용히 밀린다.
/// 시간을 더하면 사다리는 그대로 두고 그 아이만 앞당겨진다.
enum Petting {
    /// 1초 쓰다듬으면 함께한 시간이 이만큼 는다(사용자 결정: 1초 = 3분).
    ///
    /// 이 값이면 인연 리본(1일)까지 약 8분, 신뢰(7일)까지 약 56분이다. 손이 묶이는 시간이라
    /// 보조 수단으로는 쓸 만하고 통째로 대체하기엔 지루하다 — **상한은 두지 않는다**(사용자 결정).
    static let secondsPerSecondHeld = 180.0

    /// 클릭과 갈리는 문턱. 이보다 짧게 누르면 예전 그대로 클릭(팝오버 열기·연타 세기)이다.
    ///
    /// 연타로 폼을 깨는 조작과 안 부딪힌다 — 그쪽은 짧은 클릭이 세 번이고 이쪽은 한 번을
    /// 길게 누르는 것이라, 시간 축에서 갈린다.
    static let holdThreshold: TimeInterval = 0.5

    /// 누른 시간 → 더해 줄 함께한 시간(초). 문턱 아래면 0 — 클릭이지 쓰다듬기가 아니다.
    ///
    /// **문턱을 뺀 만큼만 센다.** 안 그러면 0.5초를 누른 순간 90초가 튀어, 클릭과 쓰다듬기의
    /// 경계에서 값이 불연속으로 점프한다.
    static func earnedSeconds(held: TimeInterval) -> Int {
        guard held >= holdThreshold else { return 0 }
        return Int((held - holdThreshold) * secondsPerSecondHeld)
    }
}
