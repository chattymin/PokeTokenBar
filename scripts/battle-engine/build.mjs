// Bundles the Pokémon Showdown simulator + entry.js into one script for JavaScriptCore.
//   cd scripts/battle-engine && npm ci && npm run build
// The output is committed, so building the app itself never needs Node.
import {build} from 'esbuild';
import {execFileSync} from 'node:child_process';
import {existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const out = fileURLToPath(new URL('../../Sources/PokeTokenBar/Resources/showdown-battle.js', import.meta.url));

await build({
  entryPoints: [fileURLToPath(new URL('entry.js', import.meta.url))],
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: 'safari17',   // macOS 14 JavaScriptCore
  outfile: out,
  banner: {js: '// Generated by scripts/battle-engine — do not edit. Contains @pkmn/sim (Pokémon Showdown, MIT).'},
  plugins: [{
    // Learnsets and event legality only feed the team validator, which battles never run: −3.6 MB.
    name: 'drop-learnsets',
    setup(b) {
      b.onLoad({filter: /[\\/](learnsets|legality)\.m?js$/}, () => ({contents: 'export const Learnsets = {};'}));
    },
  }],
});

// Smoke-test in the real engine when it is available (macOS).
const jsc = '/System/Library/Frameworks/JavaScriptCore.framework/Versions/A/Helpers/jsc';
if (existsSync(jsc)) {
  execFileSync(jsc, [fileURLToPath(new URL('smoke.js', import.meta.url)), '--', out], {stdio: 'inherit'});
}
